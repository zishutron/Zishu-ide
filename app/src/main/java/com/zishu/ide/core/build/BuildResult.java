package com.zishu.ide.core.build;

import com.zishu.ide.core.validation.ValidationReport;

import java.io.File;
import java.util.ArrayList;
import java.util.List;

/**
 * Outcome of a build. {@code success} is true only when {@code apk} is a file that was created by
 * the engine and passed {@link ApkInspector}; there is no other way to construct a successful result.
 */
public final class BuildResult {
    public final boolean success;
    public final boolean cancelled;
    public final File apk;
    public final ApkInspector.Info apkInfo;
    public final long durationMs;
    public final String engineId;
    public final String variant;
    /** One-line reason for a failure, or null on success. */
    public final String errorTitle;
    public final List<BuildLogAnalyzer.Finding> findings;
    public final ValidationReport validation;
    public final String log;
    public final String runUrl;
    /** How the APK is signed, e.g. "Debug key (generated by the Android Gradle Plugin)". */
    public final String signing;

    private BuildResult(boolean success, boolean cancelled, File apk, ApkInspector.Info apkInfo, long durationMs,
                        String engineId, String variant, String errorTitle, List<BuildLogAnalyzer.Finding> findings,
                        ValidationReport validation, String log, String runUrl, String signing) {
        this.success = success;
        this.cancelled = cancelled;
        this.apk = apk;
        this.apkInfo = apkInfo;
        this.durationMs = durationMs;
        this.engineId = engineId;
        this.variant = variant;
        this.errorTitle = errorTitle;
        this.findings = findings;
        this.validation = validation;
        this.log = log;
        this.runUrl = runUrl;
        this.signing = signing;
    }

    public static BuildResult success(File apk, ApkInspector.Info info, long durationMs, String engineId,
                                      String variant, String log, String runUrl, String signing) {
        if (apk == null || !apk.isFile() || info == null) {
            throw new IllegalArgumentException("A successful build needs a real, inspected APK file");
        }
        return new BuildResult(true, false, apk, info, durationMs, engineId, variant, null,
                new ArrayList<BuildLogAnalyzer.Finding>(), null, log, runUrl, signing);
    }

    public static BuildResult failure(String title, long durationMs, String engineId, String variant, String log,
                                      List<BuildLogAnalyzer.Finding> findings, String runUrl) {
        return new BuildResult(false, false, null, null, durationMs, engineId, variant, title,
                findings == null ? new ArrayList<BuildLogAnalyzer.Finding>() : findings, null, log, runUrl, null);
    }

    public static BuildResult invalid(ValidationReport report, long durationMs, String engineId, String variant) {
        String title = report.errors().isEmpty() ? "Validation failed" : report.errors().get(0).message;
        return new BuildResult(false, false, null, null, durationMs, engineId, variant, title,
                new ArrayList<BuildLogAnalyzer.Finding>(), report, report.format(), null, null);
    }

    public static BuildResult cancelled(long durationMs, String engineId, String variant, String log, String runUrl) {
        return new BuildResult(false, true, null, null, durationMs, engineId, variant, "Build cancelled",
                new ArrayList<BuildLogAnalyzer.Finding>(), null, log, runUrl, null);
    }
}
